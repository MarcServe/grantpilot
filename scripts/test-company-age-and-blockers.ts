import assert from "node:assert/strict";
import { companyAgeYears } from "../lib/company-age";
import { deriveDecisionSignals } from "../lib/grant-decision-signals";
import { grantBlockerAction } from "../lib/grant-blocker-actions";
const now = new Date("2026-10-23T12:00:00Z");
assert.equal(companyAgeYears({ incorporationDate: "2021-10-24" }, now), 4);
assert.equal(companyAgeYears({ incorporationDate: "2021-10-23" }, now), 5);
assert.equal(companyAgeYears({ incorporationDate: "2021-10-22" }, now), 5);
assert.equal(companyAgeYears({ yearEstablished: 2020 }, now), 6);
assert.equal(companyAgeYears({ incorporationDate: "2021-10-24", yearEstablished: 1990 }, now), 4);
assert.equal(companyAgeYears({ incorporationDate: "not a date" }, now), null);
assert.equal(companyAgeYears({ incorporationDate: "2030-01-01" }, now), null);
assert.equal(companyAgeYears({ yearEstablished: 0 }, now), null);
const signals = deriveDecisionSignals({ score: 85, scoringSource: "openai", missingCriteria: [], improvementPlan: { gaps: [], actions: ["Confirm incorporation date", "Prepare a budget"] } });
assert.equal(signals.primaryBlocker, null, "suggested actions are not evidence of a blocker");
assert.deepEqual(signals.profileFactsNeeded, []);
const actual = deriveDecisionSignals({ score: 65, scoringSource: "openai", missingCriteria: ["Must trade for 3 years"] });
assert.equal(actual.primaryBlocker, "Must trade for 3 years");
const route = grantBlockerAction("Company age evidence required", "grant-1", { incorporationDate: "2021-10-23" });
assert.equal(route.label, "Review grant requirement");
assert.match(route.href, /grants\/grant-1/);
assert.match(grantBlockerAction("Company age missing", "grant-1", {}).href, /profile\?/);
console.log("Company-age calculations and blocker/action separation passed");
