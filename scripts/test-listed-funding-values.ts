import assert from "node:assert/strict";
import { resolveGrantFundingValue, formatGrantFundingValue, summarizeGrantValues, comparableAwardAverages } from "../lib/grant-value";
const legacy = resolveGrantFundingValue({ amount: 25000, fundingValueType: null });
assert.equal(legacy.amount, 25000);
assert.equal(legacy.type, "unknown");
assert.equal(legacy.countsTowardApplicantTotal, false);
assert.match(formatGrantFundingValue(legacy), /25,000/);
assert.match(formatGrantFundingValue(legacy), /verify terms/);
assert.doesNotMatch(formatGrantFundingValue(legacy), /Up to|£/);
assert.equal(resolveGrantFundingValue({ amount: 20000, applicantMaxAmount: 25000 }).amount, 25000);
assert.equal(resolveGrantFundingValue({ amount: 25000, programmeTotalAmount: 5000000 }).type, "programme_total");
assert.equal(resolveGrantFundingValue({ amount: 25000, fundingValueType: "applicant_max", programmeTotalAmount: 5000000 }).type, "applicant_max");
assert.match(formatGrantFundingValue(resolveGrantFundingValue({ applicantMaxAmount: 25000, currency: "GBP" })), /Up to GBP\s*25,000/);
const unknownCurrency = summarizeGrantValues([{ amount: 25000 }, { applicantMaxAmount: 10000 }, { programmeTotalAmount: 5000000 }]);
assert.equal(unknownCurrency.total, 0);
assert.equal(unknownCurrency.knownCount, 1);
assert.equal(unknownCurrency.unknownCurrencyCount, 3);
assert.deepEqual(unknownCurrency.currencyTotals, []);
assert.deepEqual(comparableAwardAverages([{ amount: 25000, currency: "GBP", opportunityType: "grant" }]), []);
assert.equal(formatGrantFundingValue(resolveGrantFundingValue({ amount: null })), "Award amount not confirmed");
assert.equal(resolveGrantFundingValue({ amount: 0 }).amount, null);
assert.equal(resolveGrantFundingValue({ amount: -100 }).amount, null);
console.log("Legacy funding visibility and confirmed-award totals checks passed");
